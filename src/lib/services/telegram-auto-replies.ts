function normalizeMessage(value: string) {
  const normalized = value
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9@/]+/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

  return normalized
    .split(" ")
    .map((token) => CHAT_TYPO_ALIASES[token] ?? token)
    .join(" ");
}

